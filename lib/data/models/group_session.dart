enum MemberRole { organizer, member }

class Member {
  const Member({
    required this.id,
    required this.displayName,
    required this.role,
    required this.memberIndex,
    this.isSelf = false,
    this.avatarId,
  });

  factory Member.fromJson(Map<String, dynamic> j) => Member(
        id: j['id'] as String,
        displayName: j['displayName'] as String,
        role: MemberRole.values.byName(j['role'] as String),
        memberIndex: j['memberIndex'] as int,
        isSelf: j['isSelf'] as bool? ?? false,
        avatarId: j['avatarId'] as String?,
      );

  final String id;
  final String displayName;
  final MemberRole role;

  /// 0–15. Packed into the BLE advertisement and the gossip bitmap.
  final int memberIndex;
  final bool isSelf;

  /// Encoded [Avatar]; null for members who haven't set one.
  final String? avatarId;

  Member copyWith({String? displayName, MemberRole? role, int? memberIndex, bool? isSelf, String? avatarId}) => Member(
        id: id,
        displayName: displayName ?? this.displayName,
        role: role ?? this.role,
        memberIndex: memberIndex ?? this.memberIndex,
        isSelf: isSelf ?? this.isSelf,
        avatarId: avatarId ?? this.avatarId,
      );

  String get initials {
    final parts = displayName.trim().split(RegExp(r'\s+'));
    if (parts.isEmpty || parts.first.isEmpty) return '?';
    if (parts.length == 1) return parts.first.substring(0, 1).toUpperCase();
    return (parts.first.substring(0, 1) + parts.last.substring(0, 1)).toUpperCase();
  }

  Map<String, dynamic> toJson() => {
        'id': id,
        'displayName': displayName,
        'role': role.name,
        'memberIndex': memberIndex,
        'isSelf': isSelf,
        'avatarId': avatarId,
      };
}

enum SessionStatus { lobby, checklist, active, completed, cancelled }

class GroupSession {
  const GroupSession({
    required this.id,
    required this.code,
    required this.name,
    required this.adventureId,
    required this.adventureName,
    required this.date,
    required this.expectedStart,
    required this.plannedSize,
    required this.organizerId,
    required this.members,
    required this.status,
    this.expectedEnd,
    this.startedAt,
    this.endedAt,
    this.simulated = true,
  });

  factory GroupSession.fromJson(Map<String, dynamic> j) => GroupSession(
        id: j['id'] as String,
        code: j['code'] as String,
        name: j['name'] as String,
        adventureId: j['adventureId'] as String,
        adventureName: j['adventureName'] as String,
        date: DateTime.parse(j['date'] as String),
        expectedStart: DateTime.parse(j['expectedStart'] as String),
        expectedEnd: j['expectedEnd'] == null
            ? null
            : DateTime.parse(j['expectedEnd'] as String),
        plannedSize: j['plannedSize'] as int,
        organizerId: j['organizerId'] as String,
        members: (j['members'] as List)
            .map((m) => Member.fromJson(m as Map<String, dynamic>))
            .toList(),
        status: SessionStatus.values.byName(j['status'] as String),
        startedAt: j['startedAt'] == null
            ? null
            : DateTime.parse(j['startedAt'] as String),
        endedAt:
            j['endedAt'] == null ? null : DateTime.parse(j['endedAt'] as String),
        simulated: j['simulated'] as bool? ?? true,
      );

  final String id;

  /// Six-character join code shown as text and QR.
  final String code;
  final String name;
  final String adventureId;
  final String adventureName;
  final DateTime date;
  final DateTime expectedStart;
  final DateTime? expectedEnd;
  final int plannedSize;
  final String organizerId;
  final List<Member> members;
  final SessionStatus status;
  final DateTime? startedAt;
  final DateTime? endedAt;

  /// True when peers are generated by [SimulatedPeerLink] rather than BLE.
  final bool simulated;

  Member? get self {
    for (final m in members) {
      if (m.isSelf) return m;
    }
    return null;
  }

  bool get selfIsOrganizer => self?.id == organizerId;

  GroupSession copyWith({
    String? name,
    List<Member>? members,
    SessionStatus? status,
    DateTime? startedAt,
    DateTime? endedAt,
    bool? simulated,
    int? plannedSize,
    String? adventureId,
    String? adventureName,
    DateTime? date,
    DateTime? expectedStart,
  }) =>
      GroupSession(
        id: id,
        code: code,
        name: name ?? this.name,
        adventureId: adventureId ?? this.adventureId,
        adventureName: adventureName ?? this.adventureName,
        date: date ?? this.date,
        expectedStart: expectedStart ?? this.expectedStart,
        expectedEnd: expectedEnd,
        plannedSize: plannedSize ?? this.plannedSize,
        organizerId: organizerId,
        members: members ?? this.members,
        status: status ?? this.status,
        startedAt: startedAt ?? this.startedAt,
        endedAt: endedAt ?? this.endedAt,
        simulated: simulated ?? this.simulated,
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'code': code,
        'name': name,
        'adventureId': adventureId,
        'adventureName': adventureName,
        'date': date.toIso8601String(),
        'expectedStart': expectedStart.toIso8601String(),
        'expectedEnd': expectedEnd?.toIso8601String(),
        'plannedSize': plannedSize,
        'organizerId': organizerId,
        'members': members.map((m) => m.toJson()).toList(),
        'status': status.name,
        'startedAt': startedAt?.toIso8601String(),
        'endedAt': endedAt?.toIso8601String(),
        'simulated': simulated,
      };
}
